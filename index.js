/* ── Aplicar traducciones al DOM ── */
function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  function setText(selector, key) {
    const el = document.querySelector(selector);
    if (!el || !t[key]) return;
    if (el.tagName === 'UL') {
      const items = Array.isArray(t[key]) ? t[key] : [t[key]];
      const lis = el.querySelectorAll('li');
      items.forEach((txt, idx) => {
        if (lis[idx]) {
          const span = lis[idx].querySelector('span:last-child') || lis[idx];
          span.textContent = txt;
        }
      });
    } else {
      el.textContent = Array.isArray(t[key]) ? t[key].join(' ') : t[key];
    }
  }
  function setAttr(selector, attr, key) {
    const el = document.querySelector(selector);
    if (el && t[key]) el.setAttribute(attr, t[key]);
  }
  function setAttrAll(selector, attr, key) {
    const els = document.querySelectorAll(selector);
    els.forEach(el => { if (t[key]) el.setAttribute(attr, t[key]); });
  }

  const navLinks = document.querySelectorAll(".NAVEGACION a[title]");
  const navKeys = ["nav_portfolio", "nav_contact", "nav_about"];
  navLinks.forEach((a, i) => { if (navKeys[i]) a.title = t[navKeys[i]]; });

  setText(".LINKS h4, .Links h4", "footer_index");
  const footerLinks = document.querySelectorAll(".LINKS nav ul li a, .Links nav ul li a");
  const footerKeys = ["footer_home", "footer_portfolio", "footer_contact", "footer_about"];
  footerLinks.forEach((a, i) => { if (footerKeys[i]) a.textContent = t[footerKeys[i]]; });

  setText(".SUSCRIBE h4, .Suscribe h4", "subscribe_title");
  setAttrAll(".SUSCRIBE input[type=submit], .Suscribe input[type=submit]", "value", "subscribe_btn");

  setText(".sigueme", "follow_me");

  const footerH4 = document.querySelector(".FOOTER h4");
  if (footerH4) footerH4.textContent = t.footer_copy;
  const footerP = document.querySelector(".FOOTER p:not(.email)");
  if (footerP) footerP.textContent = t.footer_design;

  setText(".welcome-message", "welcome");
  setText(".ULTIMOS", "latest");

  setText(".Personal > p", "about_personal");
  setText(".Laboral  > p", "about_work");
  setText(".Academico > p", "about_academic");
  setText(".Hobies   > p", "about_hobbies");
  setText(".info-personal", "info_personal");
  setText(".info-laboral", "info_work");
  setText(".info-academico", "info_academic");
  setText(".info-hobies", "info_hobbies");

  setText(".ULTIMOS", "works_all");
  const cardHeaders = document.querySelectorAll(".trabajo-card_nombre");
  const cardKeys = ["works_tex", "works_model", "works_draw", "works_edit"];
  cardHeaders.forEach((h, i) => { if (cardKeys[i]) h.textContent = t[cardKeys[i]]; });

  setText(".precios-titulo", "prices_title");
  setText(".formulario-titulo", "form_title");

  const labels = document.querySelectorAll(".pedir label");
  const labelKeys = ["form_name", "form_email", "form_phone", "form_date", "form_product", "form_desc", "form_payment"];
  labels.forEach((l, i) => { if (labelKeys[i]) l.textContent = t[labelKeys[i]]; });

  setAttrAll(".pedir input[type=submit], .pedir .enviarboton", "value", "form_send");
}

/* ── Selector de idioma ── */
function buildLangSelector() {
  const selector = document.createElement("div");
  selector.id = "lang-selector";
  selector.style.cssText = "display:flex; align-items:center; gap:4px; font-size:13px; font-weight:600; letter-spacing:0.05em;";

  const langs = [
    { code: "es", label: "ES" },
    { code: "en", label: "EN" },
    { code: "ru", label: "RU" },
  ];

  const current = localStorage.getItem("idioma") || "es";

  langs.forEach(({ code, label }, idx) => {
    const btn = document.createElement("button");
    btn.textContent = label;
    btn.dataset.lang = code;
    btn.style.cssText = `
      background: none; border: none; cursor: pointer;
      font-size: 13px; font-weight: 600; padding: 2px 6px;
      border-radius: 4px; transition: all 0.3s; color: inherit;
      opacity: ${code === current ? "1" : "0.4"};
      text-decoration: ${code === current ? "underline" : "none"};
    `;
    btn.addEventListener("click", () => {
      localStorage.setItem("idioma", code);
      applyTranslations(code);
      selector.querySelectorAll("button").forEach(b => {
        b.style.opacity = b.dataset.lang === code ? "1" : "0.4";
        b.style.textDecoration = b.dataset.lang === code ? "underline" : "none";
      });
    });
    selector.appendChild(btn);

    if (idx < langs.length - 1) {
      const sep = document.createElement("span");
      sep.textContent = "|";
      sep.style.opacity = "0.3";
      selector.appendChild(sep);
    }
  });

  return selector;
}

/* ── Control de música ── */
function buildMusicControl() {
  const audio = new Audio('Imaganes/whoosh-short-pan-right-to-left-locran-1-00-00.mp3');
  audio.loop = true;
  audio.volume = 0.5;

  const wrap = document.createElement('div');
  wrap.style.cssText = 'display:flex; align-items:center; gap:6px;';

  const btn = document.createElement('button');
  btn.textContent = '▶';
  btn.style.cssText = `
    background: none; border: none; cursor: pointer;
    font-size: 13px; color: inherit; padding: 2px 4px;
    opacity: 0.5; transition: opacity 0.3s;
  `;

  const slider = document.createElement('input');
  slider.type = 'range';
  slider.min = 0;
  slider.max = 1;
  slider.step = 0.01;
  slider.value = 0.5;
  slider.style.cssText = 'width:55px; cursor:pointer; color:red; opacity:0.5;';

  btn.addEventListener('click', () => {
    if (audio.paused) {
      audio.play();
      btn.textContent = '⏸';
      btn.style.opacity = '1';
      slider.style.opacity = '1';
    } else {
      audio.pause();
      btn.textContent = '▶';
      btn.style.opacity = '0.5';
      slider.style.opacity = '0.5';
    }
  });

  slider.addEventListener('input', () => {
    audio.volume = slider.value;
  });

  wrap.appendChild(btn);
  wrap.appendChild(slider);
  return wrap;
}

/* ── Inyectar todo en el header ── */
function injectSelector() {
  const settings = document.querySelector(
    ".SETTIGNS, .Settings, [class*='setting' i], [class*='Setting']"
  );
  if (!settings) return;

  const wrapper = document.createElement("div");
  wrapper.style.cssText = "display:flex; align-items:center; gap:12px;";

  const inputToggle = settings.querySelector("input[type=checkbox]");
  const labelToggle = settings.querySelector("label.toggle");
  if (inputToggle && labelToggle) {
    wrapper.appendChild(inputToggle);
    wrapper.appendChild(labelToggle);
  }

  wrapper.appendChild(buildMusicControl());
  wrapper.appendChild(buildLangSelector());

  settings.innerHTML = "";
  settings.appendChild(wrapper);
}

/* ── Modo oscuro/claro ── */
function initDarkMode() {
  const toggle = document.getElementById("lightmode-toggle");
  if (!toggle) return;
  const saved = localStorage.getItem("modoClaro");
  if (saved === "true") {
    toggle.checked = true;
    document.body.classList.add("light-mode");
  } else {
    document.body.classList.remove("light-mode");
  }
  toggle.addEventListener("change", () => {
    localStorage.setItem("modoClaro", toggle.checked);
    if (toggle.checked) {
      document.body.classList.add("light-mode");
    } else {
      document.body.classList.remove("light-mode");
    }
  });
}

/* ── Slider Fullscreen ── */
function initSliderFullscreen() {
  const wrapper = document.getElementById("sliderWrapper");
  const closeBtn = document.getElementById("closeSlider");
  const slider = document.getElementById("slider");
  const slides = document.querySelectorAll(".slide");

  if (!wrapper || !closeBtn || !slider) return;

  // Abrir fullscreen al hacer clic en cualquier slide
  slides.forEach(slide => {
    slide.addEventListener("click", (e) => {
      if (e.target.tagName === "IMG" || e.target.tagName === "A") {
        e.preventDefault();
        e.stopPropagation();
        wrapper.classList.add("active");
      }
    });
  });

  // Cerrar con botón
  closeBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    wrapper.classList.remove("active");
  });

  // Cerrar con ESC
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && wrapper.classList.contains("active")) {
      wrapper.classList.remove("active");
    }
  });

  // Cerrar al hacer clic fuera (en el fondo oscuro)
  wrapper.addEventListener("click", (e) => {
    if (e.target === wrapper) {
      wrapper.classList.remove("active");
    }
  });
}

/* ── INIT ── */
document.addEventListener("DOMContentLoaded", () => {
  initDarkMode();
  injectSelector();
  initSliderFullscreen();
  const lang = localStorage.getItem("idioma") || "es";
  applyTranslations(lang);
});