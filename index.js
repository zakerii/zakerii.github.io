// Dynamic Cloudflare Links Sync for Social Footer
function applyLinksToFooter(links) {
  if (!Array.isArray(links)) return;
  const socialNavs = document.querySelectorAll('nav.redes ul, .Redes ul, .SOCIAL ul, .social-links ul');
  socialNavs.forEach(ul => {
    links.forEach(item => {
      const titleUpper = (item.title || '').toUpperCase();
      let existingA = null;
      if (titleUpper.includes('YOUTUBE')) existingA = ul.querySelector('a[title*="YOUTUBE"]');
      else if (titleUpper.includes('TWITCH')) existingA = ul.querySelector('a[title*="TWITCH"]');
      else if (titleUpper.includes('INSTAGRAM')) existingA = ul.querySelector('a[title*="INSTAGRAM"]');
      else if (titleUpper.includes('ARTSTATION')) existingA = ul.querySelector('a[title*="ARTSTATION"]');
      else if (titleUpper.includes('TWITTER') || titleUpper.includes('X')) existingA = ul.querySelector('a[title="X"], a[title*="TWITTER"]');
      else if (titleUpper.includes('GITHUB')) existingA = ul.querySelector('a[title*="GITHUB"]');

      if (existingA && item.url) {
        existingA.href = item.url.startsWith('http') ? item.url : 'https://' + item.url;
      }
    });
  });
}

async function syncSocialLinks() {
  try {
    const cached = localStorage.getItem('zakerii_cached_links');
    if (cached) {
      try { applyLinksToFooter(JSON.parse(cached)); } catch(e){}
    }

    const resp = await fetch('/api/links');
    if (!resp.ok) return;
    const links = await resp.json();
    if (Array.isArray(links) && links.length > 0) {
      localStorage.setItem('zakerii_cached_links', JSON.stringify(links));
      applyLinksToFooter(links);
    }
  } catch (e) {
    // Keep static fallback
  }
}
document.addEventListener('DOMContentLoaded', syncSocialLinks);
