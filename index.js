/* ── Aplicar traducciones completas al DOM ── */
function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  const setText = (sel, val) => {
    document.querySelectorAll(sel).forEach(el => {
      if (val !== undefined) el.textContent = val;
    });
  };

  const setAttr = (sel, attr, val) => {
    document.querySelectorAll(sel).forEach(el => {
      if (val !== undefined) el.setAttribute(attr, val);
    });
  };

  // 1. Navigation
  const navLinks = document.querySelectorAll(".NAVEGACION a[title]");
  const navKeys = ["nav_portfolio", "nav_contact", "nav_about"];
  navLinks.forEach((a, i) => { if (navKeys[i]) a.title = t[navKeys[i]]; });

  // 2. Footer
  setText(".LINKS h4, .Links h4", t.footer_index);
  const footerLinks = document.querySelectorAll(".LINKS nav ul li a, .Links nav ul li a");
  const footerKeys = ["footer_home", "footer_portfolio", "footer_contact", "footer_about"];
  footerLinks.forEach((a, i) => { if (footerKeys[i]) a.textContent = t[footerKeys[i]]; });

  setText(".SUSCRIBE h4, .Suscribe h4", t.subscribe_title);
  setText(".SUSCRIBE label, .Suscribe label", t.subscribe_label);
  setAttr(".SUSCRIBE input[type=submit], .Suscribe input[type=submit]", "value", t.subscribe_btn);
  setText(".sigueme", t.follow_me);

  setText(".FOOTER h4", t.footer_copy);
  const footerP = document.querySelector(".FOOTER p:not(.email)");
  if (footerP) footerP.textContent = t.footer_design;

  // 3. Home page elements
  setText(".welcome-message", t.welcome);
  setText(".ULTIMOS", t.latest);

  // 4. Portfolio page (trabajos.html)
  if (window.location.pathname.includes("trabajos") || document.getElementById("portfolioGrid")) {
    setText("h1.page-title", t.portfolio_page_title);
    setText("p.page-subtitle", t.portfolio_page_subtitle);

    const searchInput = document.getElementById("portfolioSearch");
    if (searchInput) searchInput.placeholder = t.portfolio_search_placeholder;

    // Filter Buttons
    const filterMap = {
      all: t.filter_all,
      "3d": t.filter_3d,
      visor3d: t.filter_visor3d,
      textura: t.filter_textura,
      anim: t.filter_anim,
      dibujo: t.filter_dibujo,
      edicion: t.filter_edicion,
      video: t.filter_video
    };
    document.querySelectorAll(".filter-btn").forEach(btn => {
      const f = btn.dataset.filter;
      if (f && filterMap[f]) btn.textContent = filterMap[f];
    });

    // 3D upload card
    setText("#upload3DCard .work-card-category", t.v3d_badge);
    setText("#upload3DCard .work-card-title", t.v3d_title);
    setText("#upload3DCard .work-card-desc", t.v3d_desc);
    setText("label[for='main3dFileInput']", t.v3d_btn);

    // Card Categories
    if (t.categories) {
      document.querySelectorAll(".work-card-category").forEach(catEl => {
        const original = catEl.getAttribute("data-original-cat") || catEl.textContent.trim();
        if (!catEl.getAttribute("data-original-cat")) {
          catEl.setAttribute("data-original-cat", original);
        }
        if (t.categories[original]) {
          catEl.textContent = t.categories[original];
        }
      });
    }
  }

  // 5. Contact page (contacto.html)
  if (window.location.pathname.includes("contacto") || document.getElementById("orderForm")) {
    setText("h1.page-title", t.contact_page_title);
    setText("p.page-subtitle", t.contact_page_subtitle);
    setText(".formulario-titulo", t.form_order_title);

    // Form labels & placeholders
    setText("label[for='nombre']", t.form_name);
    setAttr("#nombre", "placeholder", t.form_name_placeholder);
    setText("label[for='email']", t.form_email);
    setText("label[for='telefono']", t.form_phone);
    setText("label[for='fecha']", t.form_date);
    setText("label[for='producto']", t.form_service);

    const serviceSelect = document.getElementById("producto");
    if (serviceSelect && serviceSelect.options.length >= 4) {
      serviceSelect.options[0].text = t.service_opt_1;
      serviceSelect.options[1].text = t.service_opt_2;
      serviceSelect.options[2].text = t.service_opt_3;
      serviceSelect.options[3].text = t.service_opt_4;
    }

    setText("label[for='desc']", t.form_desc);
    setAttr("#desc", "placeholder", t.form_desc_placeholder);
    setText("label[for='pago']", t.form_payment);
    setText("label[for='terms']", t.form_terms);
    setText("#submitBtn", t.form_send);

    // Pricing card
    setText(".pricing-title", t.pricing_title);
    const priceItems = document.querySelectorAll(".pricing-card .price-item");
    const pricesData = [
      { name: t.price_1_name, cost: t.price_1_cost },
      { name: t.price_2_name, cost: t.price_2_cost },
      { name: t.price_3_name, cost: t.price_3_cost },
      { name: t.price_4_name, cost: t.price_4_cost },
      { name: t.price_5_name, cost: t.price_5_cost },
    ];
    priceItems.forEach((item, idx) => {
      if (pricesData[idx]) {
        const spans = item.querySelectorAll("span");
        if (spans.length >= 2) {
          spans[0].textContent = pricesData[idx].name;
          spans[1].textContent = pricesData[idx].cost;
        }
      }
    });
  }

  // 6. About page (about.html)
  if (window.location.pathname.includes("about") || document.querySelector(".about-grid")) {
    setText("h1.page-title", t.about_page_title);
    setText("p.page-subtitle", t.about_page_subtitle);
    setText(".about-card > p:nth-of-type(2)", t.about_bio_short);
    setText(".about-card .btn-submit", t.about_contact_btn);

    const tabMap = {
      personal: t.tab_personal,
      laboral: t.tab_laboral,
      academico: t.tab_academico,
      hobbies: t.tab_hobbies
    };
    document.querySelectorAll(".about-tab-btn").forEach(btn => {
      const tab = btn.dataset.tab;
      if (tab && tabMap[tab]) btn.textContent = tabMap[tab];
    });

    const updateAboutList = (sel, items) => {
      const ul = document.querySelector(sel);
      if (!ul || !Array.isArray(items)) return;
      const lis = ul.querySelectorAll("li");
      items.forEach((txt, idx) => {
        if (lis[idx]) {
          const span = lis[idx].querySelector("span:last-child") || lis[idx];
          span.textContent = txt;
        }
      });
    };

    updateAboutList(".info-personal", t.info_personal);
    updateAboutList(".info-laboral", t.info_work);
    updateAboutList(".info-academico", t.info_academic);
    updateAboutList(".info-hobbies, .info-hobies", t.info_hobbies);
  }
}

/* ── Modern Cyberpunk Language Selector ── */
function buildLangSelector() {
  const selector = document.createElement("div");
  selector.id = "lang-selector";
  selector.style.cssText = `
    display: inline-flex;
    align-items: center;
    background: rgba(13, 17, 28, 0.85);
    border: 1px solid rgba(0, 240, 255, 0.28);
    border-radius: 20px;
    padding: 2px 4px;
    gap: 3px;
    box-shadow: 0 4px 15px rgba(0, 0, 0, 0.4);
    backdrop-filter: blur(8px);
  `;

  const langs = [
    { code: "es", label: "ES", flag: "🇪🇸" },
    { code: "en", label: "EN", flag: "🇬🇧" },
    { code: "ru", label: "RU", flag: "🇷🇺" },
  ];

  const current = localStorage.getItem("idioma") || "es";

  langs.forEach(({ code, label, flag }) => {
    const btn = document.createElement("button");
    btn.dataset.lang = code;
    btn.innerHTML = `<span style="font-size: 13px; line-height: 1;">${flag}</span> <span>${label}</span>`;

    function updateStyle(isActive) {
      btn.style.cssText = `
        border: 1px solid ${isActive ? 'rgba(0, 240, 255, 0.65)' : 'transparent'};
        background: ${isActive ? 'rgba(0, 240, 255, 0.18)' : 'transparent'};
        color: ${isActive ? '#00f0ff' : 'rgba(255, 255, 255, 0.65)'};
        box-shadow: ${isActive ? '0 0 10px rgba(0, 240, 255, 0.35)' : 'none'};
        font-size: 11px;
        font-weight: 700;
        letter-spacing: 0.05em;
        padding: 4px 9px;
        border-radius: 16px;
        cursor: pointer;
        transition: all 0.25s ease;
        display: inline-flex;
        align-items: center;
        gap: 4px;
        line-height: 1;
        outline: none;
      `;
    }

    updateStyle(code === current);

    btn.addEventListener("mouseenter", () => {
      if (btn.dataset.lang !== localStorage.getItem("idioma")) {
        btn.style.color = "#fff";
        btn.style.background = "rgba(255, 255, 255, 0.08)";
      }
    });

    btn.addEventListener("mouseleave", () => {
      if (btn.dataset.lang !== localStorage.getItem("idioma")) {
        updateStyle(false);
      }
    });

    btn.addEventListener("click", () => {
      localStorage.setItem("idioma", code);
      applyTranslations(code);
      selector.querySelectorAll("button").forEach(b => {
        const isCurrent = b.dataset.lang === code;
        b.style.border = isCurrent ? '1px solid rgba(0, 240, 255, 0.65)' : '1px solid transparent';
        b.style.background = isCurrent ? 'rgba(0, 240, 255, 0.18)' : 'transparent';
        b.style.color = isCurrent ? '#00f0ff' : 'rgba(255, 255, 255, 0.65)';
        b.style.boxShadow = isCurrent ? '0 0 10px rgba(0, 240, 255, 0.35)' : 'none';
      });
    });

    selector.appendChild(btn);
  });

  return selector;
}

/* ── Control de música ── */
function buildMusicControl() {
  const audio = new Audio('Imaganes/whoosh-short-pan-right-to-left-locran-1-00-00.mp3');
  audio.loop = true;
  audio.volume = 0.5;

  const wrap = document.createElement('div');
  wrap.style.cssText = 'display:flex; align-items:center; gap:6px;';

  const btn = document.createElement('button');
  btn.textContent = '▶';
  btn.style.cssText = `
    background: none; border: none; cursor: pointer;
    font-size: 13px; color: inherit; padding: 2px 4px;
    opacity: 0.5; transition: opacity 0.3s;
  `;

  const slider = document.createElement('input');
  slider.type = 'range';
  slider.min = 0;
  slider.max = 1;
  slider.step = 0.01;
  slider.value = 0.5;
  slider.style.cssText = 'width:55px; cursor:pointer; color:red; opacity:0.5;';

  btn.addEventListener('click', () => {
    if (audio.paused) {
      audio.play().catch(() => {});
      btn.textContent = '⏸';
      btn.style.opacity = '1';
      slider.style.opacity = '1';
    } else {
      audio.pause();
      btn.textContent = '▶';
      btn.style.opacity = '0.5';
      slider.style.opacity = '0.5';
    }
  });

  slider.addEventListener('input', () => {
    audio.volume = slider.value;
  });

  wrap.appendChild(btn);
  wrap.appendChild(slider);
  return wrap;
}

/* ── Inyectar todo en el header ── */
function injectSelector() {
  const settings = document.querySelector(
    ".SETTIGNS, .Settings, [class*='setting' i], [class*='Setting']"
  );
  if (!settings) return;

  const wrapper = document.createElement("div");
  wrapper.style.cssText = "display:flex; align-items:center; gap:12px;";

  const inputToggle = settings.querySelector("input[type=checkbox]");
  const labelToggle = settings.querySelector("label.toggle");
  if (inputToggle && labelToggle) {
    wrapper.appendChild(inputToggle);
    wrapper.appendChild(labelToggle);
  }

  wrapper.appendChild(buildMusicControl());
  wrapper.appendChild(buildLangSelector());

  settings.innerHTML = "";
  settings.appendChild(wrapper);
}

/* ── Modo oscuro/claro ── */
function initDarkMode() {
  const toggle = document.getElementById("lightmode-toggle");
  if (!toggle) return;
  const saved = localStorage.getItem("modoClaro");
  if (saved === "true") {
    toggle.checked = true;
    document.body.classList.add("light-mode");
  } else {
    document.body.classList.remove("light-mode");
  }
  toggle.addEventListener("change", () => {
    localStorage.setItem("modoClaro", toggle.checked);
    if (toggle.checked) {
      document.body.classList.add("light-mode");
    } else {
      document.body.classList.remove("light-mode");
    }
  });
}

/* ── Slider Fullscreen ── */
function initSliderFullscreen() {
  const wrapper = document.getElementById("sliderWrapper");
  const closeBtn = document.getElementById("closeSlider");
  const slider = document.getElementById("slider");
  const slides = document.querySelectorAll(".slide");

  if (!wrapper || !closeBtn || !slider) return;

  slides.forEach(slide => {
    slide.addEventListener("click", (e) => {
      if (e.target.tagName === "IMG" || e.target.tagName === "A") {
        e.preventDefault();
        e.stopPropagation();
        wrapper.classList.add("active");
      }
    });
  });

  closeBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    wrapper.classList.remove("active");
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && wrapper.classList.contains("active")) {
      wrapper.classList.remove("active");
    }
  });

  wrapper.addEventListener("click", (e) => {
    if (e.target === wrapper) {
      wrapper.classList.remove("active");
    }
  });
}

/* ── Email click handler: copy & open Gmail ── */
function initEmailCopy() {
  document.querySelectorAll(".email a").forEach(link => {
    link.addEventListener("click", (e) => {
      e.preventDefault();
      const email = link.textContent.trim();
      navigator.clipboard.writeText(email).then(() => {
        const originalText = link.textContent;
        link.textContent = "¡Copiado / Copied! ✓";
        link.style.color = "var(--primary, #00f0ff)";
        setTimeout(() => {
          link.textContent = originalText;
          link.style.color = "";
        }, 2000);
      }).catch(() => {});
      window.open(`https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(email)}`, "_blank");
    });
  });
}

